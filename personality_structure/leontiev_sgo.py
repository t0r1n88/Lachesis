def calc_level(result):
    """
    Функция для подсчета уровня
    :param value:
    :return:
    """

    if 1 <= result <= 20:
        return f'1-20%'
    elif 21 <= result <= 40:
        return f'21-40%'
    elif 41 <= result <= 60:
        return f'41-60%'
    elif 61 <= result <= 80:
        return f'61-80%'
    else:
        return f'81-100%'


